/*逆序乘积式
【问题描述】

若两个正整数的乘积，等于两正整数各自逆序后的乘积，则称其为逆序乘积式。编写程序读入两个正整数，然后判断这两个正整数能否构成逆序乘积式。假设两个正整数的乘积不会超过int数据类型的表示范围。

【输入形式】

从控制台输入以一个空格分隔的两个正整数。

【输出形式】

若两个正整数能够构成逆序乘积式，则输出两个正整数及其逆序的乘积形式，并且中间用一个等号相连；若不能构成逆序乘积式，则输出两个正整数及其逆序的乘积形式，并且中间用一个不等号相连。
注意：输出的字符之间没有空格分隔。若逆序后最高位为0，则为0的最高位不输出。

【样例输入1】

12 693
【样例输出1】

12*693=21*396
【样例1说明】

输入的两个正整数为12和693，其乘积为8316。将这两个正整数逆序后分别为21和396，其乘积为8316。两者乘积相等，所以输出12*693=21*396。

【样例输入2】

185 1300
【样例输出2】

185*1300!=581*31
【样例2说明】

输入的两个正整数为185和1300，其乘积为240500。将这两个正整数逆序后分别为581和31，其乘积为18011。两者乘积不相等，所以输出185*1300!=581*31。
*/

#include <iostream> 
using namespace std;

int main()
{
    int a,b,c,d,temp;
    cin>>a>>b;

  
    temp=a;
    c=0;
    while(temp>0)
    {
        c=c*10+temp%10;
        temp/=10;
    }

    temp=b;
    d=0;
    while(temp>0)
    {
        d=d*10+temp%10;
        temp/=10;
    }

    if(a*b==c*d)
    	cout<<a<<"*"<<b<<"="<<c<<"*"<<d;
    else
    	cout<<a<<"*"<<b<<"!="<<c<<"*"<<d;

     return 0;
}



#include<iostream>
using namespace std;
// 用数字运算计算逆序数
int reverseNum(int n) 
{
    int rev = 0;
    while (n > 0) 
    {
        rev = rev * 10 + n % 10;  // 取出最后一位并添加到逆序数
        n /= 10;                  // 移除最后一位
    }
    return rev;
}

int main() {
    int a, b;
    cin >> a >> b;
    
    int ra = reverseNum(a), rb = reverseNum(b);
    long long p1 = 1LL * a * b, p2 = 1LL * ra * rb;
    
    cout << a << "*" << b << (p1 == p2 ? "=" : "!=") << ra << "*" << rb << endl;
    
    return 0;
}